import { View } from "react-native";
import { PenTool, Sparkles } from "lucide-react-native";
import { useOnboardingStore } from "@/store/onboarding-store";
import { SelectList, SelectRow } from "@/components/onboarding/SelectRow";
import { StepTitle } from "@/components/onboarding/StepTitle";

export default function StepSetupType() {
  const { setupType, setField } = useOnboardingStore();

  return (
    <View>
      <StepTitle
        title="How do you want to"
        highlight="start?"
        subtitle="Choose how to build your training program. You can change it later."
      />
      <SelectList>
        <SelectRow
          title="Smart Plan"
          description="Auto-generated by our AI based on your profile and goals."
          icon={Sparkles}
          selected={setupType === "smart"}
          onPress={() => setField("setupType", "smart")}
        />
        <SelectRow
          title="Custom Plan"
          description="Build your own routines from the exercise library."
          icon={PenTool}
          selected={setupType === "custom"}
          onPress={() => setField("setupType", "custom")}
        />
      </SelectList>
    </View>
  );
}
